#!/usr/bin/env node
/* Build the throwaway wrap-check harness data.
 *
 * Reads .scratch/spine-engine/evidence/<slug>/run.json (read-only), emits:
 *   books.js              book inputs for the prototype renderer
 *   renderer-export.js    verbatim copy of the prototype renderer with a
 *                         one-line internal-export hook appended (source file
 *                         is never modified)
 */
import fs from "node:fs";
import crypto from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const checkDir = path.resolve(here, "..");
const engineDir = path.resolve(checkDir, "..");          // .scratch/spine-engine
const evidenceDir = path.join(engineDir, "evidence");
const rendererSrc = path.resolve(
  engineDir, "..", "spine-cover-art-prototype", "app-renderers", "renderer", "renderer.js"
);

const manifest = JSON.parse(fs.readFileSync(path.join(evidenceDir, "manifest.json"), "utf8"));
const summary = JSON.parse(fs.readFileSync(path.join(evidenceDir, "summary.json"), "utf8"));
const summaryBySlug = new Map(summary.map((s) => [s.slug, s]));

function jpegSize(file) {
  const d = fs.readFileSync(file);
  let i = 2;
  while (i < d.length) {
    if (d[i] !== 0xff) { i++; continue; }
    const m = d[i + 1];
    if (m === 0xd8 || m === 0xd9) { i += 2; continue; }
    const len = d.readUInt16BE(i + 2);
    if (m >= 0xc0 && m <= 0xc3) {
      return { height: d.readUInt16BE(i + 5), width: d.readUInt16BE(i + 7) };
    }
    i += 2 + len;
  }
  throw new Error("no SOF in " + file);
}

const books = manifest.map((m) => {
  const dir = path.join(evidenceDir, m.slug);
  const run = JSON.parse(fs.readFileSync(path.join(dir, "run.json"), "utf8"));
  const s = summaryBySlug.get(m.slug) || {};
  const artSize = jpegSize(path.join(dir, "art.jpg"));
  const srcSize = jpegSize(path.join(dir, "source.jpg"));
  const sha = (f) => crypto.createHash("sha256").update(fs.readFileSync(f)).digest("hex");
  const artSha = sha(path.join(dir, "art.jpg"));
  const srcSha = sha(path.join(dir, "source.jpg"));
  const rel = "../evidence/" + m.slug + "/";
  return {
    slug: m.slug,
    title: m.title,
    author: m.author,
    pages: m.pages,
    source: rel + "source.jpg",
    sourceNote: "evidence source.jpg",
    art: rel + "art.jpg",
    artWidth: artSize.width,
    artHeight: artSize.height,
    sourceWidth: srcSize.width,
    sourceHeight: srcSize.height,
    spine: rel + "spine-2x.jpg",
    fallback: rel + "fallback-spine.jpg",
    cropBox: run.final.crop_box_work,
    route: run.final.route,
    verdict: run.final.verdict,
    reasons: run.decision_reasons,
    maskCoverage: run.mask.coverage_pct,
    detectionBoxes: run.mask.detection_boxes,
    spineLumaStd: run.qa.chosen.spine.luma_std,
    spineEdge: run.qa.chosen.spine.edge_density,
    spineOcr: run.qa.chosen.spine_residual_ocr,
    cropMaskCoverage: run.qa.chosen.crop_mask_coverage_pct,
    paletteCorr: run.qa.chosen.palette_corr,
    artSha256: artSha,
    sourceSha256: srcSha,
    artIsSource: artSha === srcSha,
    execution: "host x86-64, ONNX Runtime CPU (evidence run)",
    provenance: "spine/ release host batch run",
    engine: run.engine,
    runtimeS: s.timings ? s.timings.total : undefined,
  };
});

const header = "/* generated by tools/build-harness.mjs — inputs from evidence/<slug>/run.json */\n";
fs.writeFileSync(
  path.join(checkDir, "books.js"),
  header + "window.WRAP_CHECK_BOOKS = " + JSON.stringify(books, null, 2) + ";\n"
);

const src = fs.readFileSync(rendererSrc, "utf8");
const tail = "})(typeof window !== \"undefined\" ? window : this);";
if (!src.includes(tail)) throw new Error("renderer tail not found");
const hook = [
  "  global.__WRAP_INTERNALS__ = {",
  "    fitVertical, metrics, contrast, readableInk, luminance, mix,",
  "    paletteFor, wrapGeometry, artCropRect, panelCrop, fallbackCrop,",
  "    SPINE_W, SPINE_H, LABELS, STYLES, SERIF, SANS,",
  "  };",
  tail,
].join("\n");
fs.writeFileSync(
  path.join(checkDir, "renderer-export.js"),
  "/* generated: verbatim copy of app-renderers/renderer/renderer.js plus a read-only internal export hook */\n" +
    src.replace(tail, hook)
);

console.log("wrote books.js (" + books.length + " books) and renderer-export.js");
