def jpeg_size(path):
    with open(path, "rb") as f:
        data = f.read()
    i = 2
    while i < len(data) - 9:
        if data[i] != 0xFF:
            i += 1
            continue
        marker = data[i + 1]
        if marker in (0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7, 0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF):
            h, w = struct.unpack(">HH", data[i + 5:i + 9])
            return w, h
        if marker in (0xD8, 0xD9) or 0xD0 <= marker <= 0xD7:
            i += 2
            continue
        length = struct.unpack(">H", data[i + 2:i + 4])[0]
        i += 2 + length
    raise ValueError("no SOF in " + path)


def main():
    books = []
    for meta in BOOKS:
        slug = meta["slug"]
        run_path = os.path.join(OUT, slug, "run.json")
        with open(run_path) as f:
            run = json.load(f)
        qa_path = os.path.join(OUT, slug, "qa.json")
        qa = {}
        if os.path.exists(qa_path):
            with open(qa_path) as f:
                qa = json.load(f)
        art_rel = f"v8-output/{slug}/art.jpg"
        art_w, art_h = jpeg_size(os.path.join(ROOT, art_rel))
        chosen = (qa.get("qa") or {}).get("chosen") or {}
        spine = chosen.get("spine") or {}
        book = {
            "slug": slug,
            "title": run["book"]["title"],
            "author": run["book"]["author"],
            "pages": run["book"]["pages"] or meta["pages"],
            "source": meta["source"],
            "sourceNote": meta["source_note"],
            "art": art_rel,
            "artWidth": art_w,
            "artHeight": art_h,
            "spine": f"v8-output/{slug}/spine-2x.jpg",
            "fallback": f"v8-output/{slug}/fallback-spine.jpg",
            "cropNative": f"v8-output/{slug}/crop-native.jpg",
            "route": run["route"],
            "verdict": run["verdict"],
            "reasons": run.get("decision_reasons") or [],
            "maskCoverage": run.get("mask", {}).get("coverage_pct"),
            "detectionBoxes": run.get("mask", {}).get("detection_boxes"),
            "cropBox": run.get("final", {}).get("crop_box_work"),
            "runtimeS": run.get("runtime_s", {}).get("total"),
            "spineLumaStd": spine.get("luma_std"),
            "spineEdge": spine.get("edge_density"),
            "spineOcr": chosen.get("spine_residual_ocr") or [],
            "sourceWidth": run.get("source", {}).get("width"),
            "sourceHeight": run.get("source", {}).get("height"),
            "workingWidth": run.get("working", {}).get("width"),
            "workingHeight": run.get("working", {}).get("height"),
            "execution": "host x86-64, ONNX Runtime CPU, v8-app 0.1.0",
            "provenance": meta["provenance"],
            "license": meta["license"],
            "holdout": meta["holdout"],
            "note": (
                "Rendered from v8-app output only: the 52 × 236 crop is the pipeline's "
                "final.crop_box_work applied to art.jpg. No new art, mask or crop is invented."
            ),
        }
        books.append(book)

    os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
    with open(os.path.join(ROOT, "data", "books.json"), "w") as f:
        json.dump({"generated": "2026-11-26", "books": books}, f, indent=2)
    with open(os.path.join(ROOT, "data", "books.js"), "w") as f:
        f.write("window.APP_RENDERER_BOOKS = ")
        json.dump(books, f, indent=2)
        f.write(";\n")
    print("wrote", len(books), "books")


if __name__ == "__main__":
    main()
